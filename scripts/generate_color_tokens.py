#!/usr/bin/env python3
"""Generate the semantic color custom properties in tailwind.css from tokens.json.

Usage:
    uv run python scripts/generate_color_tokens.py          # rewrite tailwind.css
    uv run python scripts/generate_color_tokens.py --check  # exit 1 when tailwind.css is stale
"""

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSS_DIR = ROOT / "frontend/src/static/css"
TOKENS = CSS_DIR / "tokens.json"
TAILWIND = CSS_DIR / "tailwind.css"
PALETTE = CSS_DIR / "config/_light_theme.scss"

BEGIN = "/* BEGIN GENERATED by scripts/generate_color_tokens.py from tokens.json. Do not edit by hand. */"
END = "/* END GENERATED color tokens */"
DARK_MODE = "org.cinemata.modes"
GROUPS = {"semantic": "Semantic roles", "legacy": "Legacy aliases"}
TRANSPARENT = {"colorSpace": "srgb", "components": [0, 0, 0], "alpha": 0}


class TokenError(ValueError):
    pass


@dataclass(frozen=True)
class Token:
    group: str
    path: tuple[str, ...]
    light: str
    dark: str

    @property
    def css_name(self):
        return css_name(self.group, self.path)


def css_name(group, path):
    """`semantic.bg.surface.default` is `--bg-surface`; `legacy` keys are already CSS names."""
    if group == "legacy":
        return path[-1]
    if path[-1] == "default":
        path = path[:-1]
    return "-".join(path)


def read_palette(scss_text):
    return set(re.findall(r"--cinemata-([a-z0-9-]+):", scss_text))


def walk(group, node, path=()):
    for key, child in node.items():
        if key.startswith("$"):
            continue
        if "$value" in child:
            yield group, (*path, key), child
        else:
            yield from walk(group, child, (*path, key))


def load_tokens(document):
    tokens = []
    for group in GROUPS:
        for _, path, raw in walk(group, document.get(group, {})):
            if raw.get("$type") != "color":
                raise TokenError(f"{group}.{'.'.join(path)}: $type must be color")
            light = raw["$value"]
            dark = raw.get("$extensions", {}).get(DARK_MODE, {}).get("dark", light)
            tokens.append(Token(group, path, light, dark))
    names = [token.css_name for token in tokens]
    duplicates = sorted({name for name in names if names.count(name) > 1})
    if duplicates:
        raise TokenError(f"two tokens share a CSS name: {', '.join(duplicates)}")
    return tokens


def css_value(value, palette, by_reference):
    if value == TRANSPARENT:
        return "transparent"
    match = re.fullmatch(r"\{([a-z0-9.-]+)\}", value) if isinstance(value, str) else None
    if not match:
        raise TokenError(f"unsupported value {value!r}")
    group, *path = match[1].split(".")
    if group == "palette":
        step = ".".join(path)
        if step not in palette:
            raise TokenError(f"{value}: no --cinemata-{step} in {PALETTE.name}")
        return f"var(--cinemata-{step})"
    target = by_reference.get(match[1])
    if target is None:
        raise TokenError(f"{value}: no such token")
    return f"var(--{target.css_name})"


def render(tokens, palette):
    by_reference = {".".join((token.group, *token.path)): token for token in tokens}

    def declarations(mode):
        lines = []
        for group, label in GROUPS.items():
            members = [t for t in tokens if t.group == group and (mode == "light" or t.dark != t.light)]
            if not members:
                continue
            lines.append(f"\t/* {label} */")
            for token in members:
                value = token.light if mode == "light" else token.dark
                lines.append(f"\t--{token.css_name}: {css_value(value, palette, by_reference)};")
        return lines

    theme = [f"\t--color-{token.css_name}: var(--{token.css_name});" for token in tokens]
    return "\n".join(
        [
            BEGIN,
            "body {",
            *declarations("light"),
            "}",
            "",
            "body.dark_theme {",
            *declarations("dark"),
            "}",
            "",
            "/* stylelint-disable-next-line at-rule-no-unknown */",
            "@theme inline {",
            *theme,
            "}",
            END,
        ]
    )


def splice(css_text, generated):
    start = css_text.find(BEGIN)
    end = css_text.find(END)
    has_one_region = css_text.count(BEGIN) == 1 and css_text.count(END) == 1
    if not has_one_region or end < start:
        raise TokenError(f"{TAILWIND.name} must contain the BEGIN and END generated markers once, in order")
    return css_text[:start] + generated + css_text[end + len(END) :]


def build(tokens_text, palette_text, css_text):
    tokens = load_tokens(json.loads(tokens_text))
    return splice(css_text, render(tokens, read_palette(palette_text)))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when tailwind.css differs from tokens.json")
    args = parser.parse_args(argv)
    current = TAILWIND.read_text()
    try:
        expected = build(TOKENS.read_text(), PALETTE.read_text(), current)
    except TokenError as error:
        print(f"{TOKENS.relative_to(ROOT)}: {error}", file=sys.stderr)
        return 1
    if expected == current:
        return 0
    if args.check:
        print(
            f"{TAILWIND.relative_to(ROOT)} is out of date with {TOKENS.relative_to(ROOT)}. "
            "Run: uv run python scripts/generate_color_tokens.py",
            file=sys.stderr,
        )
        return 1
    TAILWIND.write_text(expected)
    print(f"wrote {TAILWIND.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
